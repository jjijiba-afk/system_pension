# ── 사망률 ────────────────────────────────────────────────────────

MORTALITY_SOURCE: Final = (
    "통계청 「2024년 생명표」(2025-12-03 공표) 공표치에 Gompertz-Makeham 곡선"
    "(qx = A + B·c^x)을 맞춘 값. 기준점은 40세→80세 생존확률 남 65.6%·여 83.3%, "
    "80세→100세 생존확률 남 1.86%·여 5.84% (기대수명 남 80.8세·여 86.6세)"
)

# Gompertz-Makeham: qx = A + B · c^x
#
# 상수항 A 가 필요한 이유가 실제로 있다. A 없이 ``B·c^x`` 만 쓰면 두 기준점
# (40→80, 80→100)을 동시에 맞출 수 없다. 40~80 을 맞추면 청·장년 사망률이
# 실제보다 30% 가까이 낮게 나온다. 젊은 층의 사망은 노화가 아니라 사고·재해가
# 대부분이라 연령에 따라 지수적으로 늘지 않기 때문인데, Makeham 이 상수항을
# 더한 이유가 바로 그것이다.
#
# 세 계수를 두 기준점에 맞추니 남녀 모두 오차 1e-6 이하로 떨어졌다. 그 결과
# 40세 사망률이 남 0.00139 · 여 0.00057 로, 통계청 완전생명표의 해당 연령대와
# 사실상 같다.
#
# 15~30세 구간은 실제보다 다소 높다. 상수항이 그 구간을 지배하기 때문이다.
# 그 연령대의 사망률은 퇴직률(15~20%)에 비해 두 자릿수 작아 채무에 보이지 않는다.
_MAKEHAM: Final[dict[str, tuple[float, float, float]]] = {
    # 성별: (A, B, c)
    "남자": (0.00092, 4.7713915085e-06, 1.121730),
    "여자": (0.00048, 3.3291732765e-07, 1.150380),
}

#: 표를 만들 연령 범위. 15세는 근로기준법상 취업 최저연령, 100세는 종전 규칙 가 쓰던 상한.
MORTALITY_AGES: Final = range(15, 101)


def _qx(sex: str, age: int) -> float:
    base, factor, ratio = _MAKEHAM[sex]
    return min(1.0, base + factor * (ratio**age))


def mortality_table() -> list[list[float]]:
    """``[연령, 남자 qx, 여자 qx]`` 행 목록.

    소수 여섯째 자리에서 끊는다. 그 아래는 채무에 보이지 않는 자릿수인데
    표만 읽기 어려워진다.
    """
    return [
        [age, round(_qx("남자", age), 6), round(_qx("여자", age), 6)]
        for age in MORTALITY_AGES
    ]


