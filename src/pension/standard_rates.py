"""기본 제공 기초율(표준률).

프로그램만 받아서는 아무것도 산출할 수 없다. 기초율 파일이 있어야 하는데, 빈
양식을 앞에 두면 첫 숫자를 무엇으로 채워야 할지 알 수 없다. 그래서 **바로 돌려
볼 수 있는 한 벌** 을 같이 넣는다.

담긴 값은 :data:`STANDARD_YEAR` 기준 **표준률 원표** 다. 승급률과 중도퇴직률은
원표가 **사업장 규모(상시근로자 300인 미만 / 이상)로 갈려 있다.** 두 벌의 차이가
작지 않아 — 30세 중도퇴직률이 11.5% 대 4.8% 다 — 아무 쪽이나 쓰면 채무가 크게
어긋난다. 그래서 규모를 고르지 않으면 값을 내주지 않는 대신, 명부 인원으로
:func:`size_for` 가 제안하게 했다.

연령 15~70세를 담는다. **원표는 110세까지 있지만 70세 행부터 값이 같다** —
표는 계단식으로 읽히므로 마지막 행이 그 이후 전 구간에 적용되고, 결과가
원표와 완전히 같다.

성격이 갈리므로 섞어 쓰지 않도록 구분해 둔다.

``사망률``
    국민 전체가 아니라 **재직자** 통계라 회사가 바꿀 것이 없다. 남녀를 나눠 쓰고
    규모로는 갈리지 않는다.

``퇴직률`` · ``승급률``
    표준률이지만 회사마다 실제 경험은 크게 다르다. 과거 3~5년 회사 경험률이
    있으면 그쪽이 우선이다. 특히 퇴직률은 채무에 가장 크게 영향을 준다.

``승급률``
    원표가 **Base-up 을 뺀** 값이다(원표 시트명 ``bu제외``). 이 모듈의
    :data:`SALARY_BASE_UP` 과 **더해져** 총 임금상승률이 되므로 이중계상이
    아니다. 회사 임금협상 이력이 있으면 Base-up 쪽을 바꾼다.

``할인율``
    결산일 현재 우량회사채 수익률이라 매 결산 바뀐다. 금리표 파일에서 읽어
    오는 것이 정확하다(:mod:`pension.yieldcurve`).
"""

