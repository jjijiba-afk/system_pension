MORTALITY_SOURCE: Final = (
    f"{STANDARD_YEAR} 사망률 (연령 15~70세). 재직자 기준, 남녀 구분. "
    "70세를 넘는 연령은 70세 값을 적용한다"
)


def mortality_table() -> list[list[float]]:
    """``[연령, 남자 qx, 여자 qx]`` 행 목록. 규모로 갈리지 않는다."""
    return [[age, male, female] for age, _w1, _w2, _p1, _p2, male, female
            in STANDARD_TABLE]


# ── 퇴직률·승급률 ─────────────────────────────────────────────────

def withdrawal_table(size: object = DEFAULT_SIZE) -> list[list[float]]:
    """``[연령, 연간 중도퇴직률]``. 사망을 제외한 값이다.

    55세부터 정년까지 가파르게 오르는 것은 임금피크·명예퇴직 구간을 반영한
    것이다(300인 미만 기준 55세 9.4% → 58세 18.7% → 61세 23.5%). 정년을 넘긴
    구간이 완만하게 내려가는 것은 그때까지 남은 사람이 계속 근무하는 쪽으로
    선택된 집단이기 때문이다.
    """
    return _size_column(size, 1, 2)


def promotion_table(size: object = DEFAULT_SIZE) -> list[list[float]]:
    """``[연령, 승급률]``. Base-up 과 **더해져** 총 임금상승률이 된다.

    원표가 Base-up 을 뺀 값이라 그대로 더하면 된다. 형태가 나이에 따라 단조롭게
    줄지 않고 20대 초·40대 중반에 봉우리가 있는데, 호봉 승급과 승진 시기가
    겹치는 구간이다.
    """
    return _size_column(size, 3, 4)


