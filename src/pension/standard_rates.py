SIZE_SMALL: Final = "300인 미만"
SIZE_LARGE: Final = "300인 이상"

SIZES: Final[tuple[str, str]] = (SIZE_SMALL, SIZE_LARGE)

DEFAULT_SIZE: Final = SIZE_SMALL
"""규모를 고르지 않았을 때 쓰는 값.

작은 쪽을 기본으로 두는 이유는 두 가지다. 국내 사업장 수로는 300인 미만이
압도적으로 많고, 이쪽 퇴직률이 높아 채무가 작게 나오므로 **틀렸을 때 눈에
띈다** — 큰 쪽을 기본으로 두면 과대계상이 조용히 지나간다.
"""

_SIZE_ALIASES: Final[dict[str, str]] = {
    "300인미만": SIZE_SMALL, "300인↓": SIZE_SMALL, "소규모": SIZE_SMALL,
    "미만": SIZE_SMALL, "SMALL": SIZE_SMALL,
    "300인이상": SIZE_LARGE, "300인↑": SIZE_LARGE, "대규모": SIZE_LARGE,
    "이상": SIZE_LARGE, "LARGE": SIZE_LARGE,
}

#: 규모가 갈리는 기준 인원. 근로기준법·표준률 원표가 같이 쓰는 선이다.
SIZE_THRESHOLD: Final = 300


def normalize_size(size: object = "") -> str:
    """규모 표기를 :data:`SIZES` 중 하나로. 못 알아보면 :data:`DEFAULT_SIZE`.

    화면·파일·CLI 가 제각기 '300인↓', '300인 미만', 'small' 로 적어 와도 같은
    열을 집어야 한다.
    """
    token = str(size or "").replace(" ", "").upper()
    if not token:
        return DEFAULT_SIZE
    return _SIZE_ALIASES.get(token, DEFAULT_SIZE)


def size_for(headcount: int) -> str:
    """명부 인원으로 규모를 제안한다. 확정이 아니라 **제안** 이다.

    표준률이 보는 것은 상시근로자 수라 산출 대상 인원과 정확히 같지는 않다
    (DC 가입자·산출 제외 직군이 빠져 있다). 화면에서 반드시 고칠 수 있어야 한다.
    """
    return SIZE_LARGE if headcount >= SIZE_THRESHOLD else SIZE_SMALL


